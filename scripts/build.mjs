import {build} from 'esbuild';
import {execFileSync} from 'node:child_process';
import {cpSync,mkdirSync,readFileSync,writeFileSync,rmSync,readdirSync} from 'node:fs';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {product} from '../src/contracts/product.mjs';
import {buildIdentity} from './metadata.mjs';
const identity=buildIdentity();
const root='dist/plugin';
rmSync('dist',{recursive:true,force:true});mkdirSync(root,{recursive:true});
execFileSync(process.execPath,['node_modules/vite/bin/vite.js','build'],{stdio:'inherit'});
mkdirSync(join(root,'dist'),{recursive:true});
writeFileSync(join(root,'dist/panel.html'),readFileSync('dist/ui/index.html'));rmSync('dist/ui',{recursive:true});
await build({entryPoints:['src/mcp/server.mjs'],outfile:join(root,'dist/server.mjs'),bundle:true,platform:'node',format:'esm',target:'node22',banner:{js:'import {createRequire as __createRequire} from "node:module";const require=__createRequire(import.meta.url);'}});
cpSync('ledger',join(root,'ledger'),{recursive:true,filter:p=>!p.includes('__pycache__')&&!p.endsWith('.pyc')});
cpSync('skills',join(root,'skills'),{recursive:true,filter:p=>!p.includes('__pycache__')&&!p.endsWith('.pyc')});
const json=(path,value)=>{mkdirSync(join(path,'..'),{recursive:true});writeFileSync(path,JSON.stringify(value,null,2)+'\n');};
const ui={displayName:product.name,shortDescription:'面向目标的智能协作工作台',longDescription:'在天枢查看项目、任务与验收证据，将任务带到聊天；直接 @天枢 查询进度、推进、核验或删除已结束任务。',developerName:product.developerName,category:product.category,capabilities:product.capabilities,defaultPrompt:'打开天枢任务中心。'};
json(join(root,'.codex-plugin/plugin.json'),{name:product.id,version:product.version,author:{name:product.developerName},description:'天枢：面向长期目标的智能协作工作台。',mcpServers:'./.mcp.json',interface:ui});
const command={command:'node',args:['${PLUGIN_ROOT}/dist/server.mjs']};
json(join(root,'.mcp.json'),{mcpServers:{[product.id]:command}});
json(join(root,'build-info.json'),identity);
const files={};
const walk=dir=>{for(const e of readdirSync(dir,{withFileTypes:true})){const p=join(dir,e.name);if(e.isDirectory())walk(p);else files[p.slice(root.length+1)]=createHash('sha256').update(readFileSync(p)).digest('hex');}};
walk(root);json('dist/build-info.json',{...identity,files});
const marketplace='dist/marketplace';mkdirSync(join(marketplace,'plugins'),{recursive:true});cpSync(root,join(marketplace,'plugins',product.id),{recursive:true});
json(join(marketplace,'.agents/plugins/marketplace.json'),{name:product.marketplace,interface:{displayName:product.name},plugins:[{name:product.id,source:{source:'local',path:`./plugins/${product.id}`},policy:{installation:'AVAILABLE',authentication:'ON_INSTALL'},category:product.category}]});
console.log(`Built ${product.id} ${product.version} (${identity.build_id}); no installation or ZIP created`);
